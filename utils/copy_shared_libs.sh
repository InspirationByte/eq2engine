#!/bin/bash

PLATFORM=x64
CONFIGURATION=Release
EXE_SUFFIX=_$CONFIGURATION
LIB_PATHS=
LIB_NAMES_PREFIX=
DESTINATION_PATH=lib

LIB_NAMES_PREFIX+=(libopenal)

export LD_LIBRARY_PATH=$LD_LIBRARY_PATH:$LIB_PATHS

mkdir $DESTINATION_PATH
for lib in ${LIB_NAMES_PREFIX[@]}
do
    cp -Lf $(ldd build/bin/${PLATFORM}/${CONFIGURATION}/DrvSyn${EXE_SUFFIX} | awk '/ => / { print $3 }' | grep ${lib}) $DESTINATION_PATH
done
